/* =========================================================
   INTERIOR DESIGNS
   ========================================================= */

export const interiorDesigns =
  interiorSpaces.flatMap((space) =>
    subDesignNames[space.slug].map(
      (name, index) => {
        const preset =
          designPresets[space.slug];

        const priceSteps = [
          0,
          50,
          100,
          150,
          200,
        ];

        const pricePerSqft =
          basePrices[space.slug] +
          priceSteps[
            index % priceSteps.length
          ];



        const dedicatedImage =
  space.slug === 'living-room'
    ? livingRoomImages[name]
    : space.slug === 'mandir'
      ? mandirImages[name]
      : `/assets/projects/interior-by-choice/${space.slug}/${slugify(
          name
        )}.webp`;

        return {
          slug: slugify(name),

          spaceSlug: space.slug,

          name,

         tagline:
  taglines[space.slug],

description:
  space.slug === 'study'
    ? studyDescriptions[index]
    : null,

pricePerSqft,

         estimatedPrice:
  space.slug === 'study'
    ? studyEstimatedPrices[index]
    : space.slug === 'tv-wall'
      ? tvEstimatedPrices[index]
      : space.slug === 'mandir'
        ? mandirEstimatedPrices[index]
        : null,

          image: dedicatedImage,

          galleryImages:
  space.slug === 'study'
    ? studyGalleryImages[name]
    : null,

          fallbackImage:
            space.image,

          colours: [
            '#efe9e2',
            '#d8c9b0',
            '#6b4a34',
            '#2e2e2e',
          ],

          features:
            preset.features,

          materialDetails:
            preset.materialDetails,
        };
      }
    )
  );




/* =========================================================
   GET SPACE
   ========================================================= */

export const getSpaceBySlug =
  (slug) =>
    interiorSpaces.find(
      (space) =>
        space.slug === slug
    );

/* =========================================================
   GET DESIGNS BY SPACE
   ========================================================= */

export const getDesignsBySpace =
  (spaceSlug) =>
    interiorDesigns.filter(
      (design) =>
        design.spaceSlug ===
        spaceSlug
    );

/* =========================================================
   GET SINGLE DESIGN
   ========================================================= */

export const getDesignBySlug =
  (spaceSlug, designSlug) =>
    interiorDesigns.find(
      (design) =>
        design.spaceSlug ===
          spaceSlug &&
        design.slug ===
          designSlug
    );

