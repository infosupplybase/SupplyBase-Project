// Writes the AC and electrician rate cards and the service FAQs (which live
// only in this frontend's data files) to a text file the website chatbot
// reads, so the bot quotes the same prices and answers the customer sees on
// the page.
//
//   npm run chatbot-data
//
// Run it after changing a price in src/data/acContent.js or
// src/data/electricalContent.js, or an FAQ in src/data/services.js, and
// commit the result. CI fails when the file is out of date.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { acCategories, acServicesByCategory, acAddonsByCategory } from '../src/data/acContent.js';
import { electricalGroups } from '../src/data/electricalContent.js';
import { activeServices } from '../src/data/services.js';

const OUT = fileURLToPath(
  new URL('../../backend/src/main/resources/chatbot/website-data.txt', import.meta.url),
);

const rupees = (n) => `₹${Number(n).toLocaleString('en-IN')}`;
const line = (item) =>
  `- ${item.label}: from ${rupees(item.price)}${item.unit ? ` per ${item.unit}` : ''}`
  + `${item.inspection ? ' inspection fee' : ''}`
  + `${item.hint ? ` (${item.hint})` : ''}`;

const out = [
  '# Generated by frontend/scripts/export-chatbot-data.mjs. Do not edit by hand.',
  '',
  'AC SERVICES PRICE LIST (book at https://supplybase.co.in/services/ac-services)',
  'Starting rates for each AC unit. Installation rates are for a Split AC; other AC types may cost differently.',
  'The technician confirms the final quote before work begins.',
];

for (const category of acCategories) {
  const services = acServicesByCategory[category.slug] || [];
  if (!services.length) continue;
  out.push('', `${category.label}:`, ...services.map(line));
  if (services.some((s) => s.inspection)) {
    out.push('Note: the inspection fee is adjusted against the repair if the customer proceeds. '
      + 'Repair labour and replacement parts are quoted by the technician after inspection.');
  }
  const addons = acAddonsByCategory[category.slug] || [];
  if (addons.length) out.push(`Optional add-ons for ${category.label}:`, ...addons.map(line));
}

out.push('', 'ELECTRICIAN PRICE LIST (book at https://supplybase.co.in/services/electrical)');
for (const group of electricalGroups) {
  const items = (group.items || []).filter((item) => item.price != null);
  if (!items.length) continue;
  out.push('', `${group.name}:`, ...items.map(line));
}

out.push('', 'FREQUENTLY ASKED QUESTIONS (answers shown on the service pages)');
for (const service of activeServices) {
  if (!service.faqs?.length) continue;
  out.push('', `${service.name}:`);
  for (const faq of service.faqs) out.push(`Q: ${faq.q}`, `A: ${faq.a}`);
}

writeFileSync(OUT, `${out.join('\n')}\n`);
console.log(`Wrote ${OUT}`);
